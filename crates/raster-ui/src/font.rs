/// Les lignes d'un glyphe, `None` hors de la table.
///
/// Un caractere absent rend `None` plutot qu'un glyphe vide : l'appelant choisit
/// s'il l'ignore ou dessine un substitut.
#[must_use]
pub fn glyph(c: char) -> Option<&'static [u8; GLYPH_HEIGHT as usize]> {
    if c < FIRST || c > LAST {
        return None;
    }
    GLYPHS.get(c as usize - FIRST as usize)
}

/// Whether a glyph's pixel at `(x, y)` is set.
#[must_use]
pub fn pixel(c: char, x: u32, y: u32) -> bool {
    if x >= GLYPH_WIDTH || y >= GLYPH_HEIGHT {
        return false;
    }
    glyph(c).is_some_and(|rows| rows[y as usize] & (1 << (GLYPH_WIDTH - 1 - x)) != 0)
}
